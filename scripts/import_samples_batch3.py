SAMPLES = [
    ("土木/建筑", "土木工程师简历范文（校招）", CIVIL),
    ("新闻/传媒", "记者编导/编辑简历范文", MEDIA),
    ("环境工程", "环境影响评价工程师简历范文", ENVIRONMENTAL),
]


def main():
    db = sqlite3.connect(DB)
    inserted = 0
    for direction, title, raw_text in SAMPLES:
        # 去重：同方向已存在则跳过
        exists = db.execute(
            "SELECT id FROM resume_samples WHERE source='web_resume_sample' AND direction=?",
            (direction,),
        ).fetchone()
        if exists:
            print(f"跳过（已存在）: {direction}")
            continue
        db.execute(
            "INSERT INTO resume_samples (id, direction, label, title, raw_text, structure, source, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            (str(uuid.uuid4()), direction, direction, title, raw_text, None, "web_resume_sample",
             datetime.now().strftime("%Y-%m-%dT%H:%M:%S")),
        )
        inserted += 1
        print(f"入库: {direction}（{len(raw_text)} 字）")

    # 对齐：医疗护理 → 医学护理
    cur = db.execute(
        "UPDATE resume_samples SET direction='医学护理', label='医学护理' "
        "WHERE source='web_resume_sample' AND direction='医疗护理'",
    )
    if cur.rowcount:
        print(f"对齐方向名: 医疗护理 → 医学护理（{cur.rowcount} 篇）")

    db.commit()
    print(f"\n新增 {inserted} 篇范文")
    db.close()


if __name__ == "__main__":
    main()
