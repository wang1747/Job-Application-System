def main():
    conn = sqlite3.connect(DB)
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS resume_samples (
            id TEXT PRIMARY KEY,
            direction TEXT NOT NULL,
            label TEXT NOT NULL,
            title TEXT NOT NULL,
            raw_text TEXT NOT NULL,
            structure TEXT,
            source TEXT NOT NULL,
            created_at TEXT NOT NULL
        )
        """
    )
    now = datetime.now().isoformat(timespec="seconds")
    for direction, title, raw in SAMPLES:
        rid = str(uuid.uuid4())
        conn.execute(
            "INSERT INTO resume_samples (id, direction, label, title, raw_text, structure, source, created_at) VALUES (?,?,?,?,?,?,?,?)",
            (rid, direction, direction, title, raw, None, "web_resume_sample", now),
        )
    conn.commit()

    n = conn.execute("SELECT COUNT(*) FROM resume_samples WHERE source='web_resume_sample'").fetchone()[0]
    print(f"web_resume_sample 入库 {n} 篇")
    for row in conn.execute("SELECT direction, title FROM resume_samples WHERE source='web_resume_sample'"):
        print(f"  [{row[0]}] {row[1]}")
    conn.close()


if __name__ == "__main__":
    main()
